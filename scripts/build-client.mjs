// Deterministic zero-dependency client build. The installed host still loads
// mcp/client.js directly; development sources and dictionaries stay separate.
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {TOOL_CATALOG,TOOL_NAMES,LITE_TOOL_NAMES} from '../mcp/catalog.mjs';
import {SETTINGS_SCHEMA,CLIENT_DEFAULT_SETTINGS} from '../mcp/settings-schema.mjs';
import {OVERLAY_STRINGS} from '../mcp/overlay-strings.mjs';

const root=new URL('../',import.meta.url);
export async function buildClient({check=false}={}) {
  const pkg=JSON.parse(await readFile(new URL('package.json',root),'utf8'));
  const dictionaries=Object.fromEntries(await Promise.all(['zh','en'].map(async locale=>[
    locale,JSON.parse(await readFile(new URL(`client/strings/${locale}.json`,root),'utf8'))
  ])));
  if(JSON.stringify(Object.keys(dictionaries.zh).sort())!==JSON.stringify(Object.keys(dictionaries.en).sort()))throw new Error('Locale dictionaries have different keys');
  for(const tool of TOOL_CATALOG)for(const locale of ['zh','en'])for(const prefix of ['tool_','toolHint_'])if(typeof dictionaries[locale][prefix+tool.name]!=='string')throw new Error(`Missing ${locale}.${prefix}${tool.name}`);
  const groups=['observe','input','windows','other'].map(group=>[group,TOOL_CATALOG.filter(tool=>tool.group===group).sort((a,b)=>a.uiOrder-b.uiOrder).map(tool=>[tool.name])]);
  const data={PLUGIN_VERSION:pkg.version,allToolNames:TOOL_NAMES,liteToolNames:LITE_TOOL_NAMES,toolGroups:groups,defaults:CLIENT_DEFAULT_SETTINGS,settingRules:Object.fromEntries(Object.entries(SETTINGS_SCHEMA).map(([key,{type,min,max,maxLength}])=>[key,{type,min,max,maxLength}])),dictionaries,defaultIndicatorTexts:Object.values(OVERLAY_STRINGS).map(table=>table.indicatorDefault)};
  let source=(await readFile(new URL('client/src/main.js',root),'utf8')).replace(/\r\n?/g,'\n');
  source=source.replace(/__WCU_BUILD_([A-Za-z_]+)__/g,(_,key)=>{
    if(!(key in data))throw new Error('Unknown build placeholder: '+key);
    // Escape HTML-sensitive characters even though this is an external script.
    return JSON.stringify(data[key],null,2).replaceAll('<','\\u003c').replaceAll('\u2028','\\u2028').replaceAll('\u2029','\\u2029');
  });
  source='// Generated by scripts/build-client.mjs. Edit client/src and client/strings.\n'+source;
  // Keep the version declaration easy to inspect in the shipped single file.
  source=source.replace(/const PLUGIN_VERSION = "([^"]+)";/,"const PLUGIN_VERSION = '$1';");
  const target=new URL('mcp/client.js',root);
  if(check){if((await readFile(target,'utf8')).replace(/\r\n?/g,'\n')!==source)throw new Error('mcp/client.js is stale; run npm run build:client');}
  else await writeFile(target,source,'utf8');
  return {version:pkg.version,localeKeys:Object.keys(dictionaries.zh).length,tools:TOOL_NAMES.length,check};
}
if(process.argv[1]&&fileURLToPath(import.meta.url)===process.argv[1])console.log(JSON.stringify(await buildClient({check:process.argv.includes('--check')})));
