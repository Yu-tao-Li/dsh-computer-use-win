import assert from 'node:assert/strict';
import { mkdtemp, readFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { installActivity } from '../mcp/activity.mjs';
import { TakeoverControl, atomicJson } from '../mcp/takeover.mjs';
import { DEFAULT_SETTINGS } from '../mcp/settings.mjs';

const root = await mkdtemp(path.join(os.tmpdir(), 'wcu-progress-'));
const activityFile = path.join(root, 'activity.json'), configFile = path.join(root, 'settings.json');
const handlers = {}, disposers = [];
const ctx = { on: (name, fn) => { handlers[name] = fn; }, effect: fn => disposers.push(fn()), logger: { error: error => { throw error; } } };
let contentSettings={...DEFAULT_SETTINGS};
// The overlay follows the language the host reports; these checks read Chinese.
let uiLocale='zh-CN';
installActivity(ctx, activityFile,{lingerMs:1500,getSettings:()=>contentSettings,getLocale:()=>uiLocale,summaryOptions:{initialDelayMs:0,request:async()=> 'Fixture summary: reading the page.'}});
const session = { id: 'fixture-a' }, agent = { session, phase: { kind: 'running', turn: 7 } };
atomicJson(configFile, { ...DEFAULT_SETTINGS, progressOverlayEnabled: true, indicatorEnabled: false, cursorIndicatorEnabled: false });
const control = new TakeoverControl({ activityFile, configFile, testMode: true });
control.layoutFile=path.join(root,'overlay-layout.json');
control.disabledForTest = false;
const event = (type, data, who = session) => handlers['session/event'](who, { type, data: { turn: 7, ...data } });
const wait = async predicate => { const until = Date.now() + 5000; do { await new Promise(r => setTimeout(r, 100)); await control.sync(); const value = await control.command('status'); if (predicate(value)) return value; } while (Date.now() < until); throw Error('Progress overlay did not update'); };
try {
  const initial = await control.command('status');
  await handlers['tools/execute']({ name: 'mcp__wincu__windows_computer_use_wait', arguments: { milliseconds: 1 }, agent }, async () => true);
  event('step/start', { step: 3 });
  event('assistant/chunk', { step: 3, chunk: { type: 'reasoning-delta', text: 'Fixture reasoning: inspecting the result.' } });
  event('assistant/chunk', { step: 3, chunk: { type: 'text-delta', text: 'Fixture reply.' } });
  event('assistant/chunk', { step: 3, chunk: { type: 'text-delta', text: 'OTHER_SESSION_SECRET' } }, { id: 'other' });
  let status = await wait(value => value.progressVisible && value.progressContent.includes('Fixture reply.'));
  assert.ok(status.progressClickThrough);
  assert.equal(status.armed, false, 'Progress alone must not arm global stop shortcuts');
  assert.equal(status.windows, 0, 'Progress is independent of the screen-edge indicator');
  assert.equal(status.foreground, initial.foreground, 'Progress window must not activate');
  assert.ok(status.progressContent.includes('Fixture reasoning'));
  assert.ok(!status.progressContent.includes('OTHER_SESSION_SECRET'));
  const artifact = path.join(root, 'progress-preview.png');
  await control.command('test_render_progress', { path: artifact, content: status.progressContent });
  contentSettings={...DEFAULT_SETTINGS,progressOverlayMode:'summary'};
  status=await wait(value=>value.progressContent.includes('Fixture summary: reading the page.'));
  assert.ok(status.progressContent.includes('AI 总结'));
  const summaryArtifact=path.join(root,'progress-summary-preview.png');
  await control.command('test_render_progress',{path:summaryArtifact,content:status.progressContent});
  // #74: switching DSH to English redraws the overlay in English on the next update.
  assert.equal(JSON.parse(await readFile(activityFile,'utf8')).locale,'zh');
  uiLocale='en-US';
  status=await wait(value=>value.progressContent.includes('AI summary'));
  assert.ok(status.progressContent.startsWith('DSH · Step 3 · ')&&!/[一-鿿]/.test(status.progressContent),status.progressContent.slice(0,120));
  await control.command('test_render_progress',{path:path.join(root,'progress-summary-preview-en.png'),content:status.progressContent});
  uiLocale='zh-CN';
  status=await wait(value=>value.progressContent.includes('AI 总结'));
  contentSettings={...DEFAULT_SETTINGS};
  await wait(value=>value.progressContent.includes('Fixture reply.')&&!value.progressContent.includes('AI 总结'));
  // DSH streams text as agent/assistant-stream frames: an abandoned attempt is
  // replaced by its retry, and another conversation's frames are ignored.
  const stream=(frame,who=session)=>handlers['agent/assistant-stream']({agent:{session:who},frame});
  stream({type:'start',attemptId:'a1',revision:1,turn:7,step:4});
  stream({type:'chunk',attemptId:'a1',revision:1,index:0,time:0,chunk:{type:'reasoning-delta',text:'ABANDONED_TEXT'}});
  stream({type:'end',attemptId:'a1',revision:2,index:1,outcome:{kind:'abandoned'}});
  stream({type:'start',attemptId:'a2',revision:3,turn:7,step:4});
  stream({type:'chunk',attemptId:'a2',revision:3,index:0,time:0,chunk:{type:'reasoning-delta',text:'Streamed reasoning for step four.'}});
  stream({type:'chunk',attemptId:'a2',revision:3,index:1,time:0,chunk:{type:'text-delta',text:'Streamed reply.'}});
  stream({type:'start',attemptId:'b1',revision:1,turn:1,step:1},{id:'other'});
  stream({type:'chunk',attemptId:'b1',revision:1,index:0,time:0,chunk:{type:'text-delta',text:'OTHER_STREAM_SECRET'}},{id:'other'});
  status=await wait(value=>value.progressContent.includes('Streamed reply.'));
  assert.ok(status.progressContent.includes('第 4 步')&&status.progressContent.includes('Streamed reasoning for step four.'));
  assert.ok(!status.progressContent.includes('ABANDONED_TEXT'),'A retried attempt replaces the abandoned text');
  assert.ok(!status.progressContent.includes('OTHER_STREAM_SECRET'));
  event('assistant/chunk', { step: 3, chunk: { type: 'reasoning-delta', text: 'x'.repeat(5000) } });
  await new Promise(r => setTimeout(r, 1100));
  const activity = JSON.parse(await readFile(activityFile, 'utf8'));
  assert.equal(activity.progress.reasoning.length, 1200, 'Stream buffering must remain bounded');
  const geometry={...DEFAULT_SETTINGS,progressOverlayOpacity:61,progressOverlayWidth:530,progressOverlayHeight:390,progressOverlayPosition:'custom',progressOverlayX:110,progressOverlayY:140,progressLockShortcut:'Ctrl+Alt+P'};
  atomicJson(configFile,geometry);
  status=await wait(value=>value.progressBounds?.width===530);
  assert.equal(status.progressOpacity,.61);assert.equal(status.progressBounds.x,110);
  await control.command('test_key',{vk:0xA2,down:true});await control.command('test_key',{vk:0xA4,down:true});
  const unlocked=await control.command('test_key',{vk:0x50,down:true});
  assert.equal(unlocked.progressLocked,false);assert.equal(unlocked.armed,false);assert.equal(unlocked.paused,false);
  assert.equal(unlocked.progressClickThrough,false,'Unlocking must change the actual native input style');
  await control.command('test_key',{vk:0x50,down:false});await control.command('test_key',{vk:0xA2,down:false});await control.command('test_key',{vk:0xA4,down:false});
  assert.equal(JSON.parse(await readFile(control.layoutFile,'utf8')).patch.progressOverlayLocked,false);
  await control.command('test_progress_layout',{x:150,y:160,width:550,height:420});
  const moved=JSON.parse(await readFile(control.layoutFile,'utf8'));
  assert.equal(moved.patch.progressOverlayWidth,550);assert.equal(moved.patch.progressOverlayX,150);
  atomicJson(configFile,{...geometry,...moved.patch});
  status=await wait(value=>value.progressBounds?.width===550);
  assert.equal(status.progressBounds.y,160);
  await control.command('test_progress_close');
  assert.equal(JSON.parse(await readFile(control.layoutFile,'utf8')).patch.progressOverlayEnabled,false);
  atomicJson(configFile,{...geometry,progressOverlayEnabled:false});
  await wait(value=>!value.progressVisible);
  // Opening from DSH settings works with the normal overlay switch off.
  atomicJson(configFile,{...geometry,progressOverlayEnabled:false,progressPreviewToken:1});
  status=await wait(value=>value.progressVisible);
  assert.equal(status.progressLocked,false);assert.equal(status.armed,false);
  atomicJson(configFile, { ...DEFAULT_SETTINGS, progressOverlayEnabled: false });
  await control.command('test_progress_close');await wait(value=>!value.progressVisible);
  atomicJson(configFile, { ...DEFAULT_SETTINGS, progressOverlayEnabled: true });
  await wait(value => value.progressVisible);
  // The finished state stays briefly so the result can be read, then goes.
  event('turn/end', {});
  status = await wait(value => value.progressVisible && value.progressContent.startsWith('DSH · 已完成'));
  assert.ok(status.progressContent.includes('Fixture reply.'), 'The final reply stays readable after the turn ends');
  assert.equal(status.armed, false, 'The lingering result holds no stop key');
  await wait(value => !value.progressVisible);
  console.log(JSON.stringify({ passed: true, hostChunkContract: 'agent/assistant-stream frames and legacy assistant/chunk', sessionIsolation: true, boundedText: true, noActivation: true, clickThrough: true, noStopHookArmed: true, liveToggle: true, endCleanup: true, finishedStateLingers: true, opacitySizePosition:true, lockShortcut:true, nativeLayoutEvents:true, persistentClose:true, settingsPreviewOpener:true, artifact, root }));
} finally { await control.close(); for (const dispose of disposers) dispose?.(); }
